// wdb 调试桩（stub ABI v1）—— 编译期契约。
//
// 为什么不事后插 import：wasm 的函数索引空间是"先 import 后定义"，
// 中途插入一个 import 会让后面所有函数索引 +1，必须重写 call / ref.func /
// element / export / start —— 那是最容易出错的一步。改成"调试构建先链接本桩"，
// 插桩时就只需要插入 `i32.const siteId; call <已存在的 import 索引>`，
// 不动任何已有索引、不新增 import。
//
// 任何语言（C / C++ / Rust / Zig）只要把 wdb-stub.c 链接进调试产物，
// 这个产物就能被 wdb 调试 —— 这就是 wdb 与编译器的唯一契约。
//
// ABI v1：
//   wdb.probe(i32 siteId) -> i32  返回本次暂停的 locals 快照地址，0 表示"这次不停"
//   wdb.pause()           -> void 快照写完后调用，阻塞直到宿主恢复

/** stub ABI 版本；改签名/语义必须+1，并与 wasm-bin.mjs、debug.worker.js 同步 */
export const WDB_ABI_VERSION = 1;

/** 调试桩 C 源码（wdb-stub.c 的内存版本，构建时直接写进 /workspace 编译） */
export const DBG_STUB_SOURCE = `/* SPDX-License-Identifier: AGPL-3.0-or-later WITH WdbStub-exception
 *
 * wdb debug stub (stub ABI v${WDB_ABI_VERSION}) — auto-generated, do not edit.
 * Generated by src/stub/wdb-stub.mjs; the canonical text lives there.
 *
 * probe: 返回本次暂停的 locals 快照地址（0 = 这次不需要暂停）
 * pause: locals 写完之后调用，真正阻塞等待宿主恢复
 */
__attribute__((import_module("wdb"), import_name("probe")))
extern int __wdb_probe(int site);

__attribute__((import_module("wdb"), import_name("pause")))
extern void __wdb_pause(void);

/* 仅用于让链接器保留上面两个 import（运行期不会被调用） */
__attribute__((used, visibility("default")))
void __wdb_dbg_anchor(void) { __wdb_probe(-1); __wdb_pause(); }
`;

/** 写一份可独立分发的 wdb-stub.c（供别的工具链直接链接） */
export function stubSourceFile() {
  return DBG_STUB_SOURCE;
}
